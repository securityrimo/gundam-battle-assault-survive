# 슬롯 확인
un={e['jp']:e for e in json.load(open(os.path.join(BASE,'_names_todo.json'),encoding='utf-8'))}
def est(ko):
    ko=ko.replace(' ','').replace('　','')
    return sum(1 if (c=='\n' or ord(c)<128) else 2 for c in ko)
bad=0; add={}
for jp,ko in KO.items():
    e=un.get(jp)
    if not e: print('  [원문없음]',repr(jp[:20])); continue
    b=est(ko)
    if b>e['slot']: print(f'  ⚠ slot{e["slot"]} {b}B | {jp[:24]} -> {ko[:24]}'); bad+=1
    else: add[jp]=ko
print(f'\n번역 {len(KO)} / 슬롯적합 {len(add)} / 초과 {bad}')
if '--write' in sys.argv and bad==0:
    sp=os.path.join(BASE,'eboot_ui_short.json')
    d=json.load(open(sp,encoding='utf-8')); d.update(add)
    json.dump(d,open(sp,'w',encoding='utf-8'),ensure_ascii=False,indent=0)
    print(f'eboot_ui_short.json 병합 → 총 {len(d)}')
