PASS={'・':'','ー':'','　':' ','、':', ','。':'.'}
def compose(jp):
    i=0;out=[];ok=True
    while i<len(jp):
        if jp.startswith('\\n',i): out.append('\\n'); i+=2; continue
        for k in KEYS:
            if jp.startswith(k,i): out.append(D[k]); i+=len(k); break
        else:
            c=jp[i]
            def _jong():
                for ch in reversed(''.join(out)):
                    if '가'<=ch<='힣': return (ord(ch)-0xAC00)%28!=0
                    if ch.isalnum(): return False
                return False
            if '가'<=c<='힣': out.append(c); i+=1   # 이미 한글화된 조각 통과
