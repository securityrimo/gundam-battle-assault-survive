def kb(s):
    n=0
    for c in s:
        if c=='\n': n+=1
        elif '가'<=c<='힣': n+=2
        else:
            try: n+=len(c.encode('cp932'))
            except: n+=2
    return n
import re
def norm(s): return re.sub(r'\{[^}]*\}','',s).replace('\n','').replace(' ','')
