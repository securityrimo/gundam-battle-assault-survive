def main() -> None:
    with io.open(PATH, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.reader(f))

    changed = 0
    found = set()
    for row in rows[1:]:
        if not row or row[0] not in POLISHED:
            continue
        row[4] = reflow_like_source(row[3], POLISHED[row[0]])
        found.add(row[0])
        changed += 1

    missing = set(POLISHED) - found
    if missing:
        raise RuntimeError(f"워크시트에서 찾지 못한 키: {sorted(missing)}")

    tmp = PATH + ".tmp"
    with io.open(tmp, "w", encoding="utf-8-sig", newline="") as f:
        csv.writer(f).writerows(rows)
    os.replace(tmp, PATH)
    print(f"미션 설명 수동 교정: {changed}개")


if __name__ == "__main__":
    main()
