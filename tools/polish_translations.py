def load_tm() -> dict[str, str]:
    tm: dict[str, str] = {}
    for path in glob.glob(os.path.join(GBU_TL, "*.json")):
        try:
            data = json.load(io.open(path, encoding="utf-8"))
        except Exception:
            continue
        if isinstance(data, dict):
            for ja, ko in data.items():
                if isinstance(ja, str) and isinstance(ko, str) and ko.strip():
                    tm.setdefault(ja, ko)
    return tm


def main() -> None:
    tm = load_tm()
    changed = 0
    for path in sorted(glob.glob(os.path.join(WS, "*.csv"))):
        with io.open(path, encoding="utf-8-sig", newline="") as f:
            reader = csv.DictReader(f)
            fields = list(reader.fieldnames or [])
            rows = list(reader)
        for row in rows:
            before = row["번역"]
            # 기존 프로젝트에서 사람이 확정한 동일 이름을 재사용한다.
            if row["kind"] in {"名前", "スキル名"} and row["원문"] in tm:
                row["번역"] = tm[row["원문"]]
            if row["원문"] in EXACT:
                row["번역"] = EXACT[row["원문"]]
            for old, new in REPLACEMENTS:
                row["번역"] = row["번역"].replace(old, new)
            if "試作" in row["원문"]:
                row["번역"] = row["번역"].replace("시작된", "시험 제작된")
                row["번역"] = re.sub(r"\b시작 ([0-9])", r"시제 \1", row["번역"])
            if "宙域" in row["원문"]:
                row["번역"] = row["번역"].replace("주역", "전투 구역")
            if "生け捕" in row["원문"]:
                row["번역"] = row["번역"].replace("잡아라", "생포하라")
                row["번역"] = row["번역"].replace("살아남는 일이다", "생포하는 것이다")
            if "照射" in row["원문"]:
                row["번역"] = row["번역"].replace("조사하여", "발사해")
            # 한글 바로 뒤에 붙은 건담은 명칭 경계를 띄운다.
            row["번역"] = re.sub(r"([가-힣])건담", r"\1 건담", row["번역"])
            if row["번역"] != before:
                changed += 1
        tmp = path + ".tmp"
        with io.open(tmp, "w", encoding="utf-8-sig", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=fields)
            writer.writeheader()
            writer.writerows(rows)
        os.replace(tmp, path)

