    for path in sorted(glob.glob(os.path.join(WS, "*.csv"))):
        with io.open(path, encoding="utf-8-sig", newline="") as f:
            for row in csv.DictReader(f):
                if not row["번역"].strip():
                    issues.append((row["key"], "공란"))
                if row["원문"].count("\\n") != row["번역"].count("\\n"):
                    issues.append((row["key"], "줄수"))
                if sorted(CODE_RE.findall(row["원문"])) != sorted(CODE_RE.findall(row["번역"])):
                    issues.append((row["key"], "코드"))
    print(f"교정 셀: {changed}")
    print(f"구조 문제: {len(issues)}")
    for issue in issues[:30]:
        print(issue)
    if issues:
        raise SystemExit(2)


